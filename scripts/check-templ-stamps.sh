#!/usr/bin/env bash
# templ generator stamp guard (precedent: scripts/check-ui-pins.sh).
#
# Fails unless every committed *_templ.go stamp matches go.mod's templ
# require version AND the generator comes from go.mod's `tool` directive.
#
# Why: the 2026-10-25 skew incident shipped a stale-generator regen
# through every existing gate — no gate noticed a committed stamp/pin
# mismatch (a bare v0.3.1020 binary regenerated 29 files with old output
# while go.mod already pinned v0.3.1070). The stamp is templ's own
# provenance marker (`// templ: version: vX.Y.Z`); when it disagrees with
# go.mod, some file in the tree was written by a different generator than
# the one this module sanctions.
#
# Caught classes:
#   1. a *_templ.go generated by a stale/different templ binary
#   2. go.mod bumped without regenerating (stamp lags the pin)
#   3. the `tool` directive removed (generator no longer pinned)
#   4. a replace directive for a-h/templ (pin discipline broken)
#
# Pure grep on go.mod + *_templ.go files: no go execution, order-
# independent, and cheap enough to run BEFORE any `templ generate` step
# (which would overwrite the evidence).
#
# Recovery: nix develop -c go tool templ generate && nix fmt
set -euo pipefail

cd "$(dirname "$0")/.."

fail=0

# The pinned generator version: go.mod's require line for a-h/templ.
pin=$(grep -E '^[[:space:]]*github\.com/a-h/templ v' go.mod | head -1 | awk '{print $2}')
if [ -z "$pin" ]; then
	echo "::error::no github.com/a-h/templ require version found in go.mod — cannot verify stamps"
	exit 1
fi

# The tool directive is the pin discipline itself (AGENTS.md: "the templ
# generator is pinned by go.mod's tool directive").
if ! grep -qE '^tool github\.com/a-h/templ/cmd/templ$' go.mod; then
	echo "::error::go.mod lost the 'tool github.com/a-h/templ/cmd/templ' directive — the generator version is no longer pinned (re-add it: go get tool github.com/a-h/templ/cmd/templ)"
	fail=1
fi

# Replace directives for the generator module break the version pin.
if grep -qE '^[[:space:]]*replace[[:space:]]+github\.com/a-h/templ([[:space:]]|$)' go.mod; then
	echo "::error::go.mod has a replace directive for github.com/a-h/templ — no replace directives in the released module (AGENTS.md)"
	fail=1
fi

stamp_files=$(find . -name '*_templ.go' -not -path './vendor/*' -not -path './.git/*' -not -path './example/*' | sort)
if [ -z "$stamp_files" ]; then
	echo "::error::no *_templ.go files found — generated output missing from the tree"
	fail=1
fi

mismatch=0
while IFS= read -r file; do
	stamp=$(grep -m1 -oE '// templ: version: v[0-9]+\.[0-9]+\.[0-9]+' "$file" || true)
	if [ -z "$stamp" ]; then
		echo "::error::$file carries no '// templ: version:' stamp — not generated by the pinned tool (or corrupted); run: nix develop -c go tool templ generate"
		mismatch=1
	elif [ "$stamp" != "// templ: version: $pin" ]; then
		echo "::error::$file stamp is '${stamp}' but go.mod pins $pin — the file was written by a different generator than the module sanctions; run: nix develop -c go tool templ generate && nix fmt"
		mismatch=1
	else
		echo "OK  $file $stamp"
	fi
done <<<"$stamp_files"

[ "$mismatch" -ne 0 ] && fail=1

total=$(printf '%s\n' "$stamp_files" | wc -l)
echo "templ stamps: $total files checked against go.mod pin $pin"
if [ "$fail" -ne 0 ]; then
	exit 1
fi
